import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {liveRoot,developmentRoot} from './lib/live_paths.mjs';
const p=JSON.parse(fs.readFileSync(path.join(developmentRoot,'createch-dev/scripts/sources/mission03_magic.json')));
assert.equal(p.schema,1);
for(const artifact of [p.nativeArtifact,p.gradedTagProvider])assert.equal(
  crypto.createHash('sha256').update(fs.readFileSync(path.join(liveRoot,artifact.file))).digest('hex'),artifact.sha256,
  'Re-review magic material authority after provider update');
const ids=p.metals.flatMap(metal=>['ore','raw'].map(form=>'occultism:crushing/'+metal+'_dust_from_'+form));
assert.equal(new Set(ids).size,20);
const output='// priority: 1790\n// Generated by createch-dev/scripts/generate_mission03_magic.mjs.\n'+
  '// Preserve TFC grades and the canonical refinery. Native 1:1 ingot crushing,\n'+
  '// rituals, storage and nonmetal spirit processing keep their native mechanics.\n'+
  'ServerEvents.recipes(event => {\n  const gradedMetalRoutes = '+JSON.stringify(ids,null,2)+'\n'+
  '  gradedMetalRoutes.forEach(id => event.remove({ id: id }))\n})\n';
const file=path.join(liveRoot,'kubejs/server_scripts/resources/magic_resource_authority.js');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(file,'utf8'),output,'Magic economy source drift');
else fs.writeFileSync(file,output);
console.log(JSON.stringify({mode:process.argv.includes('--check')?'check':'write',gradedMetalRoutes:ids.length}));
